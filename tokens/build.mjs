// Builds CSS custom properties from the DTCG tokens in this folder.
//
//   build/css/primitives.css      raw values, on :root
//   build/css/theme-<name>.css    semantic roles per theme (references primitives)
//   build/css/components.css      component tokens (references semantic roles)
//   build/css/all.css             all of the above in the correct load order
//
// The CSS is also copied into projects/ng-a11y/themes/ because ng-packagr can only
// package assets from inside the library's own folder.
//
// Components reference semantic variables with var(), so switching a theme
// only needs the theme's selector to match; no component CSS changes.
import StyleDictionary from 'style-dictionary';
import { formattedVariables } from 'style-dictionary/utils';
import { cpSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
const buildPath = join(root, 'build/css/');
const PREFIX = 'a11y';

/** Per-theme selectors. The first rule is the explicit opt-in; `system` follows the OS setting. */
const themes = {
  light: {
    colorScheme: 'light',
    rules: [{ selector: ':root, [data-theme="light"]' }],
  },
  dark: {
    colorScheme: 'dark',
    rules: [
      { selector: '[data-theme="dark"]' },
      { atRule: '@media (prefers-color-scheme: dark)', selector: ':root:not([data-theme])' },
    ],
  },
  'high-contrast': {
    colorScheme: 'light dark',
    rules: [
      { selector: '[data-theme="high-contrast"]' },
      { atRule: '@media (prefers-contrast: more)', selector: ':root:not([data-theme])' },
    ],
  },
};

const banner = '/* Generated by tokens/build.mjs from tokens/*.json. Do not edit. */\n';

StyleDictionary.registerFormat({
  name: 'css/a11y-rules',
  format: ({ dictionary, options }) => {
    const vars = (indent) =>
      formattedVariables({ format: 'css', dictionary, outputReferences: true, usesDtcg: true })
        .split('\n')
        .map((l) => indent + l.trim())
        .join('\n');
    const scheme = (indent) => (options.colorScheme ? `${indent}color-scheme: ${options.colorScheme};\n` : '');
    const blocks = options.rules.map(({ selector, atRule }) =>
      atRule
        ? `${atRule} {\n  ${selector} {\n${scheme('    ')}${vars('    ')}\n  }\n}\n`
        : `${selector} {\n${scheme('  ')}${vars('  ')}\n}\n`,
    );
    return banner + blocks.join('\n');
  },
});

const fromFile = (re) => (token) => re.test(token.filePath);

async function build({ name, source, filter, destination, options }) {
  const sd = new StyleDictionary({
    log: { verbosity: 'silent' },
    usesDtcg: true,
    source: source.map((s) => join(root, s)),
    platforms: {
      css: {
        prefix: PREFIX,
        transformGroup: 'css',
        buildPath,
        files: [{ destination, format: 'css/a11y-rules', filter, options }],
      },
    },
  });
  await sd.buildAllPlatforms();
  console.log(`  ${name.padEnd(14)} -> build/css/${destination}`);
}

console.log('Building tokens');
await build({
  name: 'primitives',
  source: ['primitives.json'],
  filter: fromFile(/primitives\.json$/),
  destination: 'primitives.css',
  options: { rules: [{ selector: ':root' }] },
});
for (const [theme, { colorScheme, rules }] of Object.entries(themes)) {
  await build({
    name: theme,
    source: ['primitives.json', `themes/${theme}.json`],
    filter: fromFile(/themes\/[^/]+\.json$/),
    destination: `theme-${theme}.css`,
    options: { rules, colorScheme },
  });
}
await build({
  name: 'components',
  source: ['primitives.json', 'themes/light.json', 'components/*.json'],
  filter: fromFile(/components\/[^/]+\.json$/),
  destination: 'components.css',
  // Also match every [data-theme] element: var() in a custom property resolves where it is
  // declared, so component tokens must be re-declared wherever a theme can change.
  options: { rules: [{ selector: ':root, [data-theme]' }] },
});

// One file with everything, in the order the cascade needs (see tokens/README.md).
const order = ['primitives', ...Object.keys(themes).map((t) => `theme-${t}`), 'components'];
const strip = (css) => css.replace(banner, '').trim();
writeFileSync(
  join(buildPath, 'all.css'),
  banner + order.map((f) => strip(readFileSync(join(buildPath, `${f}.css`), 'utf8'))).join('\n\n') + '\n',
);
console.log('  all            -> build/css/all.css');

const libThemes = join(root, '../projects/ng-a11y/themes');
mkdirSync(libThemes, { recursive: true });
cpSync(buildPath, libThemes, { recursive: true });
console.log('  copied         -> projects/ng-a11y/themes/');
